def strip_comments(query: str) -> str:
    """Blank out KQL ``//`` line comments, leaving string literals untouched.

    Needed so the provenance header that ``convert_sigma_to_kql`` prepends
    (``// Generated by ...``) is never mistaken for column references. A
    ``//`` inside a string literal (``'https://...'``) is not a comment and is
    kept. String literals themselves are deliberately *not* stripped — see
    the over-approximation note in the README.
    """
    out: list[str] = []
    i = 0
    n = len(query)
    while i < n:
        ch = query[i]
        if query.startswith("//", i):
            end = query.find("\n", i)
            end = n if end == -1 else end
            out.append(" " * (end - i))
            i = end
            continue
        if ch in "'\"":
            j = i + 1
            while j < n and query[j] != ch:
                j += 2 if query[j] == "\\" else 1
            end = min(j + 1, n)
            out.append(query[i:end])
            i = end
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _extract_referenced_columns(query: str, known_tables: set[str]) -> list[str]:
    """Best-effort regex extraction of identifiers that look like column references.

    This is intentionally an over-approximation: anything that looks like a bare
    identifier and isn't a KQL keyword or a known table name gets returned. The
    output is deduplicated and stable-ordered.
    """
    found: list[str] = []
    seen: set[str] = set()
    for match in _IDENTIFIER_RE.finditer(strip_comments(query)):
        ident = match.group(0)
        if ident in seen:
            continue
        lowered = ident.lower()
        if lowered in _KQL_RESERVED:
            continue
        if ident in known_tables:
            continue
        if ident.isdigit():
            continue
        seen.add(ident)
        found.append(ident)
    return found


def _evaluate(
    query: str,
    table: str,
    columns: dict[str, str],
    known_tables: set[str],
) -> dict[str, Any]:
    column_names = set(columns.keys())
    referenced = _extract_referenced_columns(query, known_tables)
    unknown = [name for name in referenced if name not in column_names]
    suggestions: dict[str, list[str]] = {}
    for name in unknown:
        close = difflib.get_close_matches(name, column_names, n=3, cutoff=0.6)
        if close:
            suggestions[name] = close
    return {
        "valid": len(unknown) == 0,
        "table": table,
        "unknown_columns": unknown,
        "suggestions": suggestions,
        "metadata": {
            "schema_column_count": len(column_names),
            "referenced_column_count": len(referenced),
        },
    }


async def run(ctx: ToolContext, raw_params: dict[str, Any]) -> dict[str, Any]:
    params = parse_input(ValidateKqlInput, raw_params)
    if params.tenant is None:
        return _run_bundled(params.query, params.table)

    targets = resolve_targets(ctx, params.tenant)
    audit_params = {
        "table": params.table,
        "query_length": len(params.query),
        "schema_source": "live",
        "tenants": targets,
    }

    async def _call(client: SentinelClient) -> dict[str, Any]:
        schema, cache_hit = await get_live_schema(client)
        columns = schema.get(params.table)
        if columns is None:
            # Don't list live table names: custom table names can be sensitive.
            raise SchemaValidationError(
                f"Table '{params.table}' does not exist in this tenant's workspace."
            )
        result = _evaluate(params.query, params.table, columns, set(schema))
        result["metadata"]["schema_source"] = "live"
        result["metadata"]["schema_cache_hit"] = cache_hit
        return result

    with audit_tool_call(TOOL_NAME, audit_params) as audit_extra:
        result = await dispatch(ctx, TOOL_NAME, targets, _call)
        audit_extra["tenant_count"] = len(targets)
        if "valid" in result:
            audit_extra["valid"] = result["valid"]
            audit_extra["unknown_count"] = len(result["unknown_columns"])
        return result


def _run_bundled(query: str, table: str) -> dict[str, Any]:
    columns = get_table_columns(table)
    audit_params = {
        "table": table,
        "query_length": len(query),
        "schema_source": "bundled",
    }
    with audit_tool_call(TOOL_NAME, audit_params) as audit_extra:
        if columns is None:
            raise SchemaValidationError(
                f"Table '{table}' is not in the bundled schema snapshot. "
                f"Known tables: {', '.join(list_tables())}. Pass `tenant` to "
                "validate against the live workspace schema instead."
            )
        result = _evaluate(query, table, columns, set(list_tables()))
        result["metadata"]["schema_source"] = "bundled"
        result["metadata"]["snapshot_date"] = snapshot_date()
        audit_extra["unknown_count"] = len(result["unknown_columns"])
        audit_extra["valid"] = result["valid"]
        return result
